        static readonly byte[][] CachedMasks=new byte[4][];
        public static byte At(int variant,float x,float y)
        {
            if(variant<0||variant>=4||x<0||y<0||x>=56||y>=48)return 0;
            if(CachedMasks[variant]==null)CachedMasks[variant]=BuildMask(variant);
            return CachedMasks[variant][(int)(y*8)*448+(int)(x*8)];
        }
        static byte[] BuildMask(int variant)
        {
            const int columns=448,rows=384;var mask=new byte[columns*rows];
            for(int y=0;y<rows;y++)for(int x=0;x<columns;x++)mask[y*columns+x]=RawAt(variant,(x+.5f)/8,(y+.5f)/8);
            // Decorative parapet caps and the outside of spring basins can form thin
            // disconnected ledges. Only the floor attached to the entrance is navigable.
            int sx=variant==3?228:36,sy=variant==3?308:196,start=sy*columns+sx;
            var seen=new bool[mask.Length];var queue=new int[mask.Length];int head=0,tail=0;
            if(mask[start]==1){seen[start]=true;queue[tail++]=start;}
            while(head<tail)
            {
                int at=queue[head++],x=at%columns,y=at/columns;
                void Visit(int next){if(mask[next]==1&&!seen[next]){seen[next]=true;queue[tail++]=next;}}
                if(x>0)Visit(at-1);if(x+1<columns)Visit(at+1);if(y>0)Visit(at-columns);if(y+1<rows)Visit(at+columns);
            }
            for(int i=0;i<mask.Length;i++)if(mask[i]==1&&!seen[i])mask[i]=0;
            return mask;
        }
        static byte RawAt(int variant,float x,float y)
        {
            if(variant<0||variant>=4||x<0||y<0||x>=56||y>=48)return 0;
            if(!Inside(Floors[variant],x,y)||Inside(Caverns[variant],x,y))return 0;
            foreach(var pool in Pools[variant])if(Inside(pool,x,y))return 2;
            if(variant==3)foreach(var footing in DepthFootprints)if(Inside(footing,x,y))return 0;
            var feet=Footings[variant];
            for(int i=0;i<feet.Length;i+=3){float dx=x-feet[i],dy=y-feet[i+1],r=feet[i+2];if(dx*dx+dy*dy<r*r)return 0;}
            return 1;
        }
        public static char[,] Create(int variant)
        {
            var a=new char[56,48];
            for(int y=0;y<48;y++)for(int x=0;x<56;x++){byte kind=At(variant,x+.5f,y+.5f);a[x,y]=kind==1?',':kind==2?'~':'W';}
            return a;
        }
        public static bool FootClear(int variant,float x,float y)
        {
            const float radius=.26f;float cy=y+.22f;
            int x0=(int)Math.Floor((x-radius)*8),x1=(int)Math.Floor((x+radius)*8);
            int y0=(int)Math.Floor((cy-radius)*8),y1=(int)Math.Floor((cy+radius)*8);
            for(int iy=y0;iy<=y1;iy++)for(int ix=x0;ix<=x1;ix++)
            {
                if(At(variant,(ix+.5f)/8,(iy+.5f)/8)==1)continue;
                float dx=Math.Max(ix/8f-x,Math.Max(0,x-(ix+1)/8f));
                float dy=Math.Max(iy/8f-cy,Math.Max(0,cy-(iy+1)/8f));
                if(dx*dx+dy*dy<=radius*radius)return false;
            }
            return true;
        }
        static bool Inside(float[] points,float x,float y)
        {
            bool inside=false;
            for(int i=0,j=points.Length-2;i<points.Length;j=i,i+=2)
                if((points[i+1]>y)!=(points[j+1]>y)&&x<(points[j]-points[i])*(y-points[i+1])/(points[j+1]-points[i+1])+points[i])inside=!inside;
            return inside;
        }
